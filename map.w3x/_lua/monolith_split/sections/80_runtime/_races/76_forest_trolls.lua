-- *  StartForestTrolls
---@return nothing
function StartForestTrolls()
	EnableTrigger(gg_trg_MassFrenzy)
	EnableTrigger(gg_trg_MassSetca)
	EnableTrigger(gg_trg_BeFaster)
	EnableTrigger(gg_trg_WantAxe)
	EnableTrigger(gg_trg_RitualPoglocenia)
	EnableTrigger(gg_trg_YarostBeg)
	EnableTrigger(gg_trg_ZacliatieOfDamage)
	EnableTrigger(gg_trg_ReturnDamage)
	EnableTrigger(gg_trg_ZacliatieOfLive)
	EnableTrigger(gg_trg_SetLifeNormal)
	EnableTrigger(gg_trg_Charge)
end