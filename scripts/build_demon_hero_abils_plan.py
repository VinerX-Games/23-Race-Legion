wts_updates = {}
checks_def = []

for aid, info in sorted(data.items()):
    p = plan[aid]
    name_str = f"|cffe4cfa3{p['name']}|r"
    hk = p['hotkey']
    hk_suffix = f" (|cffffffff{hk}|r)" if hk else ""
    lvls = info['levels']
    
    # 1. name
    nid = sid(info['name_raw'])
    if nid:
        wts_updates[nid] = name_str
        checks_def.append((aid, 'name', nid, name_str))
        
    # 2. researchtip / researchubertip
    rtid = sid(info.get('researchtip'))
    if rtid:
        rt_val = f"|cffe4cfa3Изучить: {p['name']}|r{hk_suffix}"
        wts_updates[rtid] = rt_val
        checks_def.append((aid, 'researchtip', rtid, rt_val))
        
    rubid = sid(info.get('researchubertip'))
    if rubid:
        lines = [f"|cffa6afb8СПОСОБНОСТЬ:|cffced4da {p['base']}|r|n"]
        for lvl in range(1, lvls + 1):
            short_eff, _ = p['levels'][lvl]
            lines.append(f"|cffa6afb8Уровень {lvl}:|cffced4da {short_eff}|r")
        rub_val = "|n".join(lines)
        wts_updates[rubid] = rub_val
        checks_def.append((aid, 'researchubertip', rubid, rub_val))
        
    # 3. tips and ubertips per level
    for lvl in range(1, lvls + 1):
        short_eff, full_eff = p['levels'][lvl]
        
        tid = sid(info['tips'][str(lvl)][0])
        if tid:
            if lvls == 1:
                t_val = f"|cffe4cfa3{p['name']}|r{hk_suffix}"
            else:
                t_val = f"|cffe4cfa3{p['name']} — уровень {lvl}|r{hk_suffix}"
            wts_updates[tid] = t_val
            checks_def.append((aid, f'tip{lvl}', tid, t_val))
            
        ubid = sid(info['ubertips'][str(lvl)][0])
        if ubid:
            ub_val = f"|cffa6afb8СПОСОБНОСТЬ:|cffced4da {full_eff}|r"
            wts_updates[ubid] = ub_val
            checks_def.append((aid, f'ubertip{lvl}', ubid, ub_val))

print(f"Constructed {len(wts_updates)} WTS updates across {len(plan)} hero abilities.")

